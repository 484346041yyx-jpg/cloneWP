function modelPreferences(raw: string): Record<string, string> {
  const root = raw.split(/^\s*\[/m)[0];
  const result: Record<string, string> = {};
  for (const name of ['model', 'model_reasoning_effort']) {
    const match = new RegExp(`^\\s*${name}\\s*=\\s*(?:"([^"\\r\\n]+)"|'([^'\\r\\n]+)')\\s*(?:#.*)?$`, 'm').exec(root);
    const value = match?.[1] ?? match?.[2];
    if (value && /^[a-zA-Z0-9._:/-]{1,160}$/.test(value)) result[name] = value;
  }
  return result;
}

export interface PlannerIsolation { directory: string; home: string; workDir: string; sdkOptions: CodexOptions; dispose: () => Promise<void> }
export async function createPlannerIsolation(options: { sourceHome?: string; tempRoot?: string; environment?: NodeJS.ProcessEnv; evidenceBundle?: EvidenceBundle } = {}): Promise<PlannerIsolation> {
  const environment = options.environment ?? process.env;
  const sourceHome = options.sourceHome ?? environment.CODEX_HOME ?? path.join(os.homedir(), '.codex');
  const tempRoot = await realpath(options.tempRoot ?? os.tmpdir());
  const directory = await mkdtemp(path.join(tempRoot, 'clonewp-planner-'));
  const home = path.join(directory, 'home'); const workDir = path.join(directory, 'work');
  let disposed = false;
  const dispose = async () => {
    if (disposed) return;
    const resolved = await realpath(directory).catch(error => { if ((error as NodeJS.ErrnoException).code === 'ENOENT') return undefined; throw error; });
    if (!resolved) { disposed = true; return; }
    if (path.dirname(resolved) !== tempRoot || !path.basename(resolved).startsWith('clonewp-planner-')) throw new Error('Refused to clean an unexpected planner auth directory');
    await rm(resolved, { recursive: true, force: true });
    disposed = true;
  };
  try {
    await mkdir(home, { mode: 0o700 }); await mkdir(workDir, { mode: 0o700 });
    await chmod(directory, 0o700).catch(() => undefined);
    await copyFile(path.join(sourceHome, 'auth.json'), path.join(home, 'auth.json')).catch(() => { throw new Error('Codex local auth.json is unavailable for the isolated planner. Authenticate Codex locally before cloning.'); });
    await chmod(path.join(home, 'auth.json'), 0o600).catch(() => undefined);
    let preferences: Record<string, string> = {};
    try { preferences = modelPreferences(await readFile(path.join(sourceHome, 'config.toml'), 'utf8')); } catch (error) { if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error; }
    const evidencePath = path.join(workDir, 'public-evidence.json');
    if (options.evidenceBundle) await writeJson(evidencePath, options.evidenceBundle);
    const servers: Record<string, { command: string; args: string[]; enabled_tools: string[]; startup_timeout_sec: number; tool_timeout_sec: number; required: boolean; default_tools_approval_mode: string; tools: Record<string, { approval_mode: string; output_token_limit: number }> }> = options.evidenceBundle ? { clonewp_evidence: { command: process.execPath, args: ['--import', import.meta.resolve('tsx'), fileURLToPath(new URL('./evidence-server.ts', import.meta.url)), evidencePath], enabled_tools: [...EVIDENCE_TOOLS], startup_timeout_sec: 30, tool_timeout_sec: 15, required: true, default_tools_approval_mode: 'prompt', tools: Object.fromEntries(EVIDENCE_TOOLS.map(name => [name, { approval_mode: 'approve', output_token_limit: 25000 }])) } } : {};
    const config = { ...PLANNER_CONFIGURATION, ...preferences, mcp_servers: servers };
    await writeFile(path.join(home, 'config.toml'), `${Object.entries(preferences).map(([key, value]) => `${key} = ${JSON.stringify(value)}`).join('\n')}\nweb_search = "disabled"\ncli_auth_credentials_store = "file"\n[mcp_servers]\n[plugins]\n[features]\n${Object.entries(PLANNER_CONFIGURATION.features).map(([key, value]) => `${key} = ${value}`).join('\n')}\n[apps._default]\nenabled = false\n`, { encoding: 'utf8', mode: 0o600 });
    const env: Record<string, string> = {};
    const allowed = new Set(['path', 'pathext', 'systemroot', 'windir', 'comspec', 'temp', 'tmp', 'userprofile', 'home', 'homedrive', 'homepath', 'localappdata', 'appdata', 'lang', 'lc_all', 'https_proxy', 'http_proxy', 'no_proxy', 'ssl_cert_file', 'ssl_cert_dir', 'node_extra_ca_certs']);
    for (const [key, value] of Object.entries(environment)) if (value !== undefined && allowed.has(key.toLowerCase())) env[key] = value;
    env.CODEX_HOME = home;
    return { directory, home, workDir, sdkOptions: { config, env }, dispose };
  } catch (error) { await dispose(); throw error; }
}

export function isForbiddenPlanningEvent(event: unknown, allowEvidence = false): boolean {
  if (!event || typeof event !== 'object') return false;
  const value = event as { type?: string; item?: { type?: string; server?: string; tool?: string } };
  if (allowEvidence && value.item?.type === 'mcp_tool_call' && value.item.server === 'clonewp_evidence' && EVIDENCE_TOOLS.includes(value.item.tool as typeof EVIDENCE_TOOLS[number])) return false;
  return !!value.type?.startsWith('item.') && !!value.item?.type && !['agent_message', 'reasoning', 'todo_list', 'error'].includes(value.item.type);
}

export class CodexPlanner {
  private thread?: Thread;
  private isolation?: PlannerIsolation;
  private controller?: AbortController;
  private round: number;
  private disposed = false;
  constructor(private readonly options: PlannerOptions) { this.round = options.firstArtifactRound ?? 0; }
  async dispose() { this.disposed = true; this.controller?.abort(); this.thread = undefined; await this.isolation?.dispose(); this.isolation = undefined; }
  async plan(evidence: PlanningEvidence) {
    if (this.disposed) throw new Error('Planner has been disposed');
    if (this.options.deadlineAt !== undefined && Date.now() >= this.options.deadlineAt) throw new Error('Total clone task time budget exhausted before Codex planning');
    const request = readablePlanningRequest(evidence, this.options.mode, this.options.maxElements, this.options.maxPromptBytes);
    const prompt = request.prompt;
    await writeJson(path.join(this.options.runDir, `plan/evidence-${this.round}.json`), { format: 'clonewp-evidence-v2', evidenceAccess: request.bundle ? 'read-only-mcp' : 'embedded', promptBytes: Buffer.byteLength(prompt), promptLimit: this.options.maxPromptBytes ?? DEFAULT_PROMPT_LIMIT, source: compactSource(evidence.source), widgetSchemas: compactWidgetSchemas(evidence.widgetSchemas) });
    if (!this.thread) {
      this.isolation ??= await createPlannerIsolation({ evidenceBundle: request.bundle });
      if (request.bundle) await writeJson(path.join(this.isolation.workDir, 'public-evidence.json'), request.bundle);
      const codex = new Codex(this.isolation.sdkOptions);
      this.thread = codex.startThread({ workingDirectory: this.isolation.workDir, skipGitRepoCheck: true, sandboxMode: 'read-only', approvalPolicy: 'never', modelReasoningEffort: 'medium', webSearchMode: 'disabled', networkAccessEnabled: false });
    }
    const input: UserInput[] = [{ type: 'text', text: prompt }, ...planningImagePaths(evidence).map(image => ({ type: 'local_image' as const, path: image }))];
    const controller = new AbortController(); this.controller = controller;
    const timeoutMs = Math.min(this.options.timeoutMs, this.options.deadlineAt === undefined ? Infinity : this.options.deadlineAt - Date.now());
    if (timeoutMs <= 0) throw new Error('Total clone task time budget exhausted before Codex submission');
    const timer = setTimeout(() => controller.abort(new Error('Codex planning timeout')), timeoutMs);
    const events: unknown[] = [];
    let final = '';
    try {
      const streamed = await this.thread.runStreamed(input, { outputSchema: modelOutputSchema, signal: controller.signal });
      for await (const event of streamed.events) {
        if (isForbiddenPlanningEvent(event, !!request.bundle)) { const rejection = new Error('Planning-only agent attempted an external action'); controller.abort(rejection); throw rejection; }
        if (event.type === 'item.started' && event.item.type === 'mcp_tool_call') this.options.log?.(`Codex evidence ${event.item.tool}`);
        if (event.type === 'item.completed' && event.item.type === 'mcp_tool_call') events.push({ type: 'evidence.read', tool: event.item.tool, status: event.item.status, arguments: event.item.arguments, resultSha256: createHash('sha256').update(JSON.stringify(event.item.result ?? event.item.error ?? null)).digest('hex') });
        if (event.type === 'turn.failed' || event.type === 'error') throw new Error(event.type === 'error' ? event.message : event.error.message);
        if (event.type === 'item.completed' && event.item.type === 'agent_message') final = event.item.text;
        if (['thread.started', 'turn.started', 'turn.completed'].includes(event.type)) { events.push(event); this.options.log?.(`Codex ${event.type}`); }
      }
      if (!final) throw new Error('Codex returned no structured plan');
      const sourceIds = new Set(evidence.source.viewports.flatMap(viewport => viewport.elements.map(element => element.id)));
      await writeJson(path.join(this.options.runDir, `plan/attempt-${this.round}.json`), { output: final, threadId: this.thread.id });
      const sourceAliases = Object.fromEntries([
        ...evidence.source.sections.map(section => [section.id, section.sourceNodeId]),
        ...evidence.source.viewports.flatMap(viewport => viewport.elements.filter(element => element.primaryOwnerId && element.primaryOwnerId !== element.id).map(element => [element.id, element.primaryOwnerId!])),
      ]);
      const validated = validatePlan(JSON.parse(final), { mode: this.options.mode, maxElements: this.options.maxElements, widgetSchemas: evidence.widgetSchemas, sourceIds, sourceAliases, allowedMedia: Array.isArray(evidence.assets) ? evidence.assets as AllowedMedia[] : [] });
      await writeJson(path.join(this.options.runDir, `plan/round-${this.round++}.json`), { ...validated, threadId: this.thread.id, events });
      return validated;
    } catch (error) {
      // SDK subprocess cancellation can mask the timer's reason as a generic AbortError.
      // Preserve that reason so orchestration does not silently retry a timed-out model call.
      if (controller.signal.aborted && controller.signal.reason instanceof Error) throw controller.signal.reason;
      throw error;
    } finally {
      clearTimeout(timer); if (this.controller === controller) this.controller = undefined;
      // Each request already contains the current recipe and measurements. Re-sending
      // a complete page into the previous thread needlessly multiplies its context.
      this.thread = undefined;
    }
  }
}
