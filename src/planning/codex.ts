/** Explicit static-page capability profile; exact live definitions and dependencies stay intact. */
export function staticPageSchemas(schemas: WidgetSchemas): WidgetSchemas {
  const excluded = /(?:motion_fx|^_transform_|shape_divider|_mask_|slideshow|background_video|background_overlay|hover|css_filters|^sticky|^wd_|^scroll_|^element_parallax|animation|^ai_|^e_display_conditions)/;
  const presentation = /^(?:_?section_|_?tabs_|_?tab_|separator_|responsive_description$|normal$|hover$)/;
  const advanced = /^_(?:margin|padding|element_(?:width|custom_width|vertical_align|id)|grid_|flex_|position|offset_|z_index|attributes|background_|border_|box_shadow_)/;
  return Object.fromEntries(Object.entries(schemas).map(([type, schema]) => {
    const controls = schema.controls ?? {};
    const selected = new Set(Object.keys(controls).filter(name => !excluded.test(name) && !presentation.test(name) && (!name.startsWith('_') || advanced.test(name))));
    const dependencies = (value: unknown): string[] => {
      if (!value || typeof value !== 'object') return [];
      if (Array.isArray(value)) return value.flatMap(dependencies);
      const refs: string[] = [];
      for (const [key, item] of Object.entries(value)) {
        const candidate = key.replace(/[!<>=]+$/, '');
        if (Object.hasOwn(controls, candidate)) refs.push(candidate);
        if (key === 'name' && typeof item === 'string' && Object.hasOwn(controls, item)) refs.push(item);
        if (typeof item === 'object') refs.push(...dependencies(item));
      }
      return refs;
    };
    for (const name of selected) for (const dependency of dependencies({ condition: controls[name].condition, conditions: controls[name].conditions })) selected.add(dependency);
    return [type, { ...schema, controls: Object.fromEntries([...selected].map(name => [name, controls[name]])) }];
  }));
}
const stable = (value: unknown): string => JSON.stringify(value && typeof value === 'object'
  ? Array.isArray(value) ? value.map(item => JSON.parse(stable(item))) : Object.fromEntries(Object.entries(value).sort(([a], [b]) => a.localeCompare(b)).map(([key, item]) => [key, item === undefined ? null : JSON.parse(stable(item))]))
  : value ?? null);
export function inlineAssetAlias(url: string): string { return `inline:${createHash('sha256').update(url).digest('hex')}`; }

interface AliasInfo { kind: string; sourceNodeIds: string[]; viewports: string[]; sha256: string; mime: string; encodedBytes: number }
interface ResourceAliaser { aliases: Record<string, AliasInfo>; value: (value: unknown) => any }
function resourceAliaser(source: SourceCapture): ResourceAliaser {
  const aliases: Record<string, AliasInfo> = {};
  const exact = new Map<string, string>();
  const register = (url: string, kind = 'image', sourceNodeIds: string[] = [], viewports: string[] = []) => {
    const alias = inlineAssetAlias(url); exact.set(url, alias);
    const old = aliases[alias];
    aliases[alias] = { kind, sourceNodeIds: [...new Set([...(old?.sourceNodeIds ?? []), ...sourceNodeIds])], viewports: [...new Set([...(old?.viewports ?? []), ...viewports])], sha256: createHash('sha256').update(url).digest('hex'), mime: /^data:([^;,]+)/i.exec(url)?.[1] ?? 'image/unknown', encodedBytes: Buffer.byteLength(url) };
    return alias;
  };
  for (const asset of source.assets) if (/^data:image\//i.test(asset.url)) register(asset.url, asset.kind, asset.sourceNodeIds, asset.viewports);
  const transform = (value: unknown): any => {
    if (typeof value === 'string') {
      if (/^data:image\//i.test(value)) return exact.get(value) ?? register(value);
      let result = value;
      for (const [url, alias] of exact) if (result.includes(url)) result = result.split(url).join(alias);
      return result;
    }
    if (Array.isArray(value)) return value.map(transform);
    if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, transform(item)]));
    return value;
  };
  return { aliases, value: transform };
}

function semanticNode(element: SourceElement, aliaser: ResourceAliaser) {
  const attributes = Object.fromEntries(Object.entries(element.attributes).filter(([key]) => ['id', 'href', 'role', 'type', 'name', 'alt', 'title', 'lang', 'dir', 'open', 'viewBox', 'd', 'fill', 'stroke'].includes(key) || key.startsWith('aria-')));
  return aliaser.value({ parentId: element.parentId, kind: element.kind, tag: element.tag, ...(element.primaryOwnerId ? { primaryOwnerId: element.primaryOwnerId } : {}),
    text: element.kind === 'container' ? '' : element.text, directText: element.directText,
    ...(element.effectiveOpacity !== undefined ? { effectiveOpacity: element.effectiveOpacity } : {}),
    ...('renderedFonts' in element && element.renderedFonts ? { renderedFonts: element.renderedFonts } : {}),
    attributes, ...(element.image ? { image: element.image } : {}), ...(element.link ? { link: element.link } : {}),
  });
}

export interface CompactSource {
  encoding: 'clonewp-evidence-v2'; url: string; title: string; warnings: string[];
  styleBase: Record<string, string>;
  stylePatches: Record<string, Record<string, string | null>>;
  nodes: Record<string, any>;
  resourceAliases: Record<string, AliasInfo>;
  resources: unknown[];
  viewports: Array<{ name: string; width: number; height: number; pageHeight: number; sections: any[]; elements: Array<{ id: string; rect: SourceElement['rect']; styleRef: string; nodeDelta?: Record<string, unknown> }>; interactions: unknown[] }>;
}

/** Required content/geometry/styles remain exact; repeated nodes/styles and responsive evidence are shared. */
export function compactSource(source: SourceCapture, aliaser = resourceAliaser(source)): CompactSource {
  const allStyles = source.viewports.flatMap(viewport => viewport.elements.map(element => aliaser.value(element.style) as Record<string, string>));
  const keys = [...new Set(allStyles.flatMap(style => Object.keys(style)))];
  const styleBase: Record<string, string> = {};
  for (const key of keys) {
    const counts = new Map<string, number>();
    for (const style of allStyles) if (Object.hasOwn(style, key)) counts.set(style[key], (counts.get(style[key]) ?? 0) + 1);
    const most = [...counts].sort((a, b) => b[1] - a[1])[0];
    if (most && most[1] > allStyles.length - [...counts.values()].reduce((sum, count) => sum + count, 0)) styleBase[key] = most[0];
  }
  const stylePatches: CompactSource['stylePatches'] = {};
  const styleByValue = new Map<string, string>();
  const nodeTable: CompactSource['nodes'] = {};
  const viewports = source.viewports.map(viewport => ({
    name: viewport.name, width: viewport.width, height: viewport.height, pageHeight: viewport.pageHeight,
    sections: viewport.sections.map(section => ({ id: section.id, sourceNodeId: section.sourceNodeId, rect: section.rect, atomIds: section.atomIds })),
    elements: viewport.elements.map(element => {
      const style = aliaser.value(element.style) as Record<string, string>;
      const patch: Record<string, string | null> = {};
      for (const key of keys) if (style[key] !== styleBase[key]) patch[key] = Object.hasOwn(style, key) ? style[key] : null;
      const fingerprint = stable(patch);
      let styleRef = styleByValue.get(fingerprint);
      if (!styleRef) { styleRef = `s${styleByValue.size}`; styleByValue.set(fingerprint, styleRef); stylePatches[styleRef] = patch; }
      const node = semanticNode(element, aliaser);
      if (!Object.hasOwn(nodeTable, element.id)) nodeTable[element.id] = node;
      const base = nodeTable[element.id];
      const nodeDelta: Record<string, unknown> = {};
      for (const key of [...new Set([...Object.keys(node), ...Object.keys(base)])]) if (stable(node[key]) !== stable(base[key])) nodeDelta[key] = Object.hasOwn(node, key) ? node[key] : null;
      return { id: element.id, rect: element.rect, styleRef, ...(Object.keys(nodeDelta).length ? { nodeDelta } : {}) };
    }),
    interactions: aliaser.value(viewport.interactions),
  }));
  return { encoding: 'clonewp-evidence-v2', url: source.url, title: source.title, warnings: source.warnings, styleBase, stylePatches, nodes: nodeTable, resourceAliases: aliaser.aliases, resources: aliaser.value(source.assets), viewports };
}

export function expandCompactSource(source: CompactSource) {
  return source.viewports.map(viewport => ({ ...viewport, elements: viewport.elements.map(element => {
    const node = { ...source.nodes[element.id] };
    for (const [key, value] of Object.entries(element.nodeDelta ?? {})) { if (value === null) delete node[key]; else node[key] = value; }
    const style = { ...source.styleBase };
    for (const [key, value] of Object.entries(source.stylePatches[element.styleRef])) { if (value === null) delete style[key]; else style[key] = value; }
    return { id: element.id, ...node, rect: element.rect, style };
  }) }));
}

export function compactWidgetSchemas(schemas: WidgetSchemas) {
  const controlDefinitions: Record<string, unknown> = {};
  const byValue = new Map<string, string>();
  const widgets = Object.fromEntries(Object.entries(schemas).map(([type, schema]) => [type, { ...schema, controls: Object.fromEntries(Object.entries(schema.controls ?? {}).map(([name, metadata]) => {
    const key = stable(metadata); let ref = byValue.get(key);
    if (!ref) { ref = `c${byValue.size}`; byValue.set(key, ref); controlDefinitions[ref] = metadata; }
    return [name, ref];
  })) }]));
  return { encoding: 'clonewp-control-dictionary-v1', controlDefinitions, widgets };
}

