/** Lossless transport dictionary; all source facts and control definitions remain present. */
export function packPlanningEvidence(value: unknown, options: { preserveKeys?: boolean } = {}) {
  const counts = new Map<string, number>();
  const visit = (item: unknown): void => {
    if (typeof item === 'string') counts.set(item, (counts.get(item) ?? 0) + 1);
    else if (Array.isArray(item)) item.forEach(visit);
    else if (item && typeof item === 'object') Object.values(item).forEach(visit);
  };
  visit(value);
  const strings = [...counts].filter(([text, count]) => text.length > 16 && count > 1 && (text.length - 8) * count > text.length + 8).map(([text]) => text);
  const refs = new Map(strings.map((text, index) => [text, `~${index.toString(36)}`]));
  const keys: string[] = [], keyRefs = new Map<string, string>();
  const encode = (item: unknown): unknown => {
    if (typeof item === 'string') return refs.get(item) ?? (item.startsWith('~') ? `~${item}` : item);
    if (Array.isArray(item)) return item.map(encode);
    if (item && typeof item === 'object') return Object.fromEntries(Object.entries(item).map(([key, child]) => {
      if (options.preserveKeys) return [key.startsWith('$') ? `$${key}` : key, encode(child)];
      let ref = keyRefs.get(key);
      if (!ref) { ref = `k${keys.length.toString(36)}`; keyRefs.set(key, ref); keys.push(key); }
      return [ref, encode(child)];
    }));
    return item;
  };
  const encoded = encode(value);
  const objectCounts = new Map<string, number>();
  const countObjects = (item: unknown): void => {
    if (!item || typeof item !== 'object') return;
    const text = JSON.stringify(item);
    if (text.length > 40) objectCounts.set(text, (objectCounts.get(text) ?? 0) + 1);
    Object.values(item).forEach(countObjects);
  };
  countObjects(encoded);
  const objects: unknown[] = [], objectRefs = new Map<string, number>();
  const share = (item: unknown): unknown => {
    if (!item || typeof item !== 'object') return item;
    const text = JSON.stringify(item);
    const shared = (objectCounts.get(text) ?? 0) > 1;
    if (shared && objectRefs.has(text)) return { $: objectRefs.get(text) };
    const result = Array.isArray(item) ? item.map(share) : Object.fromEntries(Object.entries(item).map(([key, child]) => [key, share(child)]));
    if (!shared) return result;
    const index = objects.length; objects.push(result); objectRefs.set(text, index);
    return { $: index };
  };
  const data = share(encoded);
  return { encoding: 'clonewp-transport-dictionary-v1', preserveKeys: options.preserveKeys === true, keys, strings, objects, data };
}

export function unpackPlanningEvidence(packed: ReturnType<typeof packPlanningEvidence>): unknown {
  const decode = (item: unknown): unknown => {
    if (typeof item === 'string') {
      if (item.startsWith('~~')) return item.slice(1);
      if (/^~[0-9a-z]+$/.test(item)) return packed.strings[parseInt(item.slice(1), 36)];
      return item;
    }
    if (item && typeof item === 'object' && '$' in item) return decode(packed.objects[(item as { $: number }).$]);
    if (Array.isArray(item)) return item.map(decode);
    if (item && typeof item === 'object') return Object.fromEntries(Object.entries(item).map(([key, child]) => [packed.preserveKeys ? (key.startsWith('$$') ? key.slice(1) : key) : packed.keys[parseInt(key.slice(1), 36)], decode(child)]));
    return item;
  };
  return decode(packed.data);
}

