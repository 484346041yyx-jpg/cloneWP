import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {loadConfig} from '../src/core/config.js';
import {WordPressClient} from '../src/wordpress/client.js';
import {discoverNative44Contracts} from '../src/native44/target-context.js';
import {usedNative44WidgetTypes} from '../src/native44/compiler.js';
import {checkNative44Environment,assertNative44Environment} from '../src/native44/environment.js';
import {NATIVE44_ALL_TYPES} from '../src/native44/catalog.js';
const dir='D:/cloneWP/references/reference-v2-2026-10-17T01-38-08-872Z-www-petsupermarket-com-0cd5b3b3';
const program=JSON.parse(await readFile(dir+'/program.json','utf8'));
const {config,credentials}=await loadConfig('D:/cloneWP');
const types=usedNative44WidgetTypes(program);
const client=new WordPressClient({targetUrl:config.targetUrl,username:credentials.wp_user,applicationPassword:credentials.wp_app_password,executionStrategy:'native44-css-handoff',allowedWidgetTypes:NATIVE44_ALL_TYPES});
const preflight=await client.preflight();
const capabilities=await discoverNative44Contracts(client,types);
const environment=checkNative44Environment(preflight,capabilities,{usedTypes:types});
assertNative44Environment(environment);
await mkdir(dir+'/target-read-only',{recursive:true});
await writeFile(dir+'/target-read-only/capabilities.json',JSON.stringify(capabilities,null,2)+'\n');
await writeFile(dir+'/target-read-only/environment.json',JSON.stringify(environment,null,2)+'\n');
console.log(JSON.stringify({status:'read-only-target-contracts-verified',usedTypes:types,remoteWrites:0,catalogQueries:0}));
